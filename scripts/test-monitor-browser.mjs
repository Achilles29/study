import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require = createRequire(import.meta.url);
const puppeteer = require(process.env.STUDY_PUPPETEER_MODULE || 'puppeteer-core');
const base = 'http://127.0.0.1:8097';
const out = process.env.STUDY_MONITOR_SCREENSHOTS;
const browser = await puppeteer.launch({executablePath:'/usr/bin/google-chrome',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
try {
 const page = await browser.newPage(); const errors=[]; page.on('pageerror', e=>errors.push(e.message));
 await page.setViewport({width:1280,height:900}); await page.goto(base+'/masuk');
 await page.type('[name="identity"]','monitor1'); await page.type('[name="password"]','Monitor-QA-Only-2026!');
 await Promise.all([page.waitForNavigation(),page.click('button[type="submit"]')]);
 await page.goto(base+'/kelola/pembelajaran/pengguna/3');
 assert.equal(await page.$eval('.admin-sidebar',e=>getComputedStyle(e).position),'fixed');
 assert.equal(await page.$eval('.admin-nav-link.active',e=>e.textContent.trim()),'Progres pengguna');
 assert.ok(await page.$eval('body',e=>!e.innerText.includes('PRIVATE FAMILY TITLE')));
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'desktop overflow');
 if(out) await page.screenshot({path:out+'/desktop.png',fullPage:true});
 await page.click('.admin-menu-toggle'); assert.equal(await page.$eval('.admin-sidebar',e=>getComputedStyle(e).display),'none');
 await page.click('.admin-menu-toggle');
 await page.setViewport({width:360,height:800});
 await page.waitForFunction(()=>getComputedStyle(document.querySelector('.admin-sidebar')).display==='none');
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile overflow');
 await page.click('.admin-menu-toggle');
 assert.equal(await page.$eval('.admin-sidebar',e=>e.getAttribute('role')),'dialog');
 assert.ok(await page.$eval('.admin-workspace',e=>e.inert));
 assert.equal(await page.evaluate(()=>document.activeElement.classList.contains('admin-drawer-close')),true);
 await page.keyboard.down('Shift'); await page.keyboard.press('Tab'); await page.keyboard.up('Shift');
 assert.ok(await page.evaluate(()=>document.querySelector('.admin-sidebar').contains(document.activeElement)),'focus trapped');
 if(out) await page.screenshot({path:out+'/mobile-drawer.png'});
 await page.keyboard.press('Escape'); assert.equal(await page.evaluate(()=>document.activeElement.classList.contains('admin-menu-toggle')),true);
 assert.equal(await page.$eval('.admin-workspace',e=>e.inert),false);
 if(out) await page.screenshot({path:out+'/mobile.png',fullPage:true});
 await page.setJavaScriptEnabled(false); await page.reload();
 assert.notEqual(await page.$eval('.admin-sidebar',e=>getComputedStyle(e).display),'none','no-JS navigation usable');
 await page.setJavaScriptEnabled(true); await page.goto(base+'/kelola/rapor/3'); await page.emulateMediaType('print');
 assert.equal(await page.$eval('.admin-sidebar',e=>getComputedStyle(e).display),'none','print hides navigation');
 await page.emulateMediaType('screen');
 await page.goto(base+'/kelola'); await Promise.all([page.waitForNavigation(),page.click('.admin-account button[type="submit"]')]);
 assert.deepEqual(errors,[],'browser exceptions');
 console.log('PASS browser: desktop/mobile layout, active menu, collapse, drawer/Escape/focus trap, no-JS fallback, print, logout.');
} finally {await browser.close();}
