2. Bagian gambar mana yang ditunjuk ketika mendengar eye?
3. Apa arti two hands?

## Cek dan ceritakan
1. Kepala.
2. Mata pada gambar.
3. Dua tangan. Kata two menunjukkan jumlah dua, dan hands adalah bentuk jamak pada frasa ini.

