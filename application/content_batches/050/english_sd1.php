Kamu mengenali beberapa nama bagian tubuh melalui gambar atau boneka. Tidak perlu menyentuh tubuh orang lain untuk latihan.

## Kosakata
head = kepala
hand = tangan
eye = mata
ear = telinga
nose = hidung
Pendamping boleh menggambar tokoh sederhana pada kertas. Tunjuk bagian gambar sambil menyebut kata Inggrisnya. Jika memakai gambar, pastikan anak tahu bagian mana yang ditunjuk.

## Satu dan lebih dari satu
One hand berarti satu tangan; two hands berarti dua tangan. Pada contoh ini, bentuk jamak hands, eyes, dan ears memakai akhiran s. Kita sedang mempelajari kata, bukan menetapkan bahwa bentuk tubuh semua orang harus sama.
Kalimat “This is a hand” dapat dipakai ketika menunjukkan gambar satu tangan. Untuk gambar dua tangan, frasa “two hands” menyebut jumlahnya.

## Contoh bersama
Pendamping berkata “Point to the nose.” Anak menunjuk hidung pada gambar. Pendamping berkata “Point to the ear.” Anak menunjuk telinga pada gambar. Tindakan yang diminta ialah menunjuk gambar, bukan memasukkan benda ke hidung atau telinga.

## Coba sendiri
