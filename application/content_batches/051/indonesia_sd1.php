Baca tulisanmu dan tanyakan: kepada siapa pesannya, apa maksudnya, dan siapa pengirimnya? Periksa spasi, huruf kapital pada nama/awal kalimat, serta tanda akhir. Jika maksudnya belum jelas, tambahkan informasi yang diperlukan, bukan informasi pribadi yang tidak relevan.

## Coba sendiri
1. Siapa pengirim pesan pada bacaan awal?
2. Apa yang diminta kepada Dito?
3. Buat satu pesan meminta izin meminjam buku dari tokoh rekaan.

## Cek dan ceritakan
1. Nara.
2. Mengembalikan buku ke rak.
3. Contoh: “Lani, bolehkah aku meminjam bukumu? Terima kasih. Raka.” Jawaban boleh berbeda asalkan penerima, maksud, dan pengirim jelas serta bahasanya santun.

## Untuk pendamping
Periksa pesan bersama anak tanpa mengambil alih semua tulisannya. Jika anak mendiktekan pesan, tuliskan lalu baca bersama; bedakan kegiatan menyusun pesan dari kemampuan menulis tangan. Jangan mengunggah data pribadi untuk latihan.

