## Cek dan ceritakan
1. Sebelum makan atau setelah menggunakan toilet.
2. Tidak. Kuman tidak selalu tampak; ikuti kebiasaan mencuci tangan pada waktu yang diperlukan.
3. Menjauh, tidak menyentuhnya, dan memberi tahu pendamping.

## Untuk pendamping
Praktik kebersihan perlu dicontohkan dan dibantu, bukan dinilai dari rasa jijik atau penampilan anak. Beri akses air/sabun yang aman. Jika anak cedera atau memiliki keluhan kesehatan, cari pertolongan yang sesuai, bukan memakai kuis sebagai diagnosis.

