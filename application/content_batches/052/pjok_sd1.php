## Ayo pahami
Tangan yang tampak bersih belum tentu bebas kuman. Cuci tangan dengan sabun dan air bersih mengalir, terutama sebelum makan dan setelah menggunakan toilet. Pendamping memperagakan membasahi tangan, memakai sabun, menggosok seluruh bagian tangan termasuk sela jari dan sekitar kuku setidaknya 20 detik, membilas, lalu mengeringkan dengan cara yang bersih.
Sabun bukan bahan makanan. Gunakan tempat cuci tangan yang aman dan jangan memanjat perabot tidak stabil untuk meraih keran. Anak boleh dibantu sesuai kebutuhan.

## Contoh bersama
Sesudah bermain, Nara hendak makan. Ia merapikan alat, mencuci tangan dengan pendamping, lalu makan. Dito melihat pecahan kaca di dekat tempat bermain. Ia tidak menyentuhnya; ia menjauh dan memberi tahu orang dewasa yang dipercaya.
Kebiasaan aktif, makanan beragam sesuai kebutuhan, minum air yang aman dan istirahat merupakan bagian kehidupan sehari-hari yang perlu dibantu keluarga. Pelajaran ini tidak menetapkan porsi makan atau latihan medis untuk setiap anak.

